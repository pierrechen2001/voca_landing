function deepMerge(base, extra) {
  return { ...base, ...extra };
}

const locales = ["zh-TW", "zh-CN", "ja", "ko", "id", "vi", "th", "es", "pt"];
const merged = {};
const tw = PACK["zh-TW"];

for (const loc of locales) {
  if (loc === "zh-TW") {
    merged[loc] = { ...tw };
  } else if (loc === "zh-CN" || loc === "ja" || loc === "ko") {
    merged[loc] = deepMerge(tw, LOCALE_OVERRIDES[loc] || {});
  } else if (["es", "id", "vi", "th", "pt"].includes(loc)) {
    const partial = JSON.parse(fs.readFileSync(path.join(localesDir, loc + ".json"), "utf8"));
    merged[loc] = deepMerge(PACK_EN, partial);
  } else {
    throw new Error("Unhandled locale: " + loc);
  }
}

const payload =
  "window.VOCA_LANDING_MERGE(" +
  JSON.stringify(merged, null, 0) +
  ");\n";

fs.writeFileSync(out, payload, "utf8");
